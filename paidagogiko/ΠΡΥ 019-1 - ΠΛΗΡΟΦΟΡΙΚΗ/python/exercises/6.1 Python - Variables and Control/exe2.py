# Άσκηση 2: α%β, α//β, (α+β)/(γδ), -((α+β)/γ)/(δ+α)

a = float(input("Δώσε τον αριθμό α: "))
b = float(input("Δώσε τον αριθμό β: "))
c = float(input("Δώσε τον αριθμό γ: "))
d = float(input("Δώσε τον αριθμό δ: "))

print("a)", a % b)
print("b)", a // b)
print("c)", (a + b) / (c * d))
print("d)", -((a + b) / c) / (d + a))
